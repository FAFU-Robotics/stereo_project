"""recorder.py —— 结果落盘（任务 1 的「左右图 + 深度数据保存」交付物）

设计要点（都是本项目踩过的坑）：
  1) 目录名用**毫秒级**时间戳 —— 秒级会在同一秒内按两次 s 时互相覆盖（早期真踩过）。
  2) ASCII PLY 的 comment 必须写在 `format` 行**之后**，且只能是 ASCII
     （写在前面 Open3D 直接报 "unable to parse header"；中文注释会 UnicodeEncodeError）。
  3) 落盘内容与既有分析脚本保持兼容：left_raw.png / right_raw.png / disparity.npy /
     depth_meter.npy / cloud.ply / meta.txt。
     注意：启用标定校正时，left/right"raw"实际是**校正后**的图像（meta 里会注明），
     这样老的对比脚本（compare_with_realsense 等）不用改。
"""

from __future__ import annotations

import json
import os
import time
from typing import Any, Dict, Optional

import cv2
import numpy as np

from .types import DepthResult


def make_session_dir(base_dir: str, tag: str = "cloud") -> str:
    """建一个毫秒级唯一目录并返回路径。"""
    now = time.time()
    stamp = time.strftime("%Y%m%d_%H%M%S", time.localtime(now))
    ms = int(round((now - int(now)) * 1000.0)) % 1000
    path = os.path.join(base_dir, f"{stamp}_{ms:03d}_{tag}")
    os.makedirs(path, exist_ok=True)
    return path


def write_ascii_ply(path: str, points: np.ndarray, colors: np.ndarray,
                    comments: Optional[list] = None) -> str:
    """写 ASCII PLY。points: (N,3) float32 米；colors: (N,3) uint8 BGR。
    ⚠️ 颜色按 RGB 写出（BGR->RGB 反转），但点云坐标**不做**任何翻转（保持相机系 y 向下）。
    """
    n = int(len(points))
    head = ["ply", "format ascii 1.0"]
    for c in (comments or []):
        ascii_c = str(c).encode("ascii", errors="ignore").decode("ascii")
        head.append(f"comment {ascii_c}")
    head += [f"element vertex {n}",
             "property float x", "property float y", "property float z",
             "property uchar red", "property uchar green", "property uchar blue",
             "end_header"]
    rgb = colors[:, ::-1].astype(np.int32) if len(colors) else np.zeros((0, 3), np.int32)
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(head) + "\n")
        for i in range(n):
            x, y, z = points[i]
            r, g, b = rgb[i] if i < len(rgb) else (128, 128, 128)
            fh.write(f"{x:.6f} {y:.6f} {z:.6f} {int(r)} {int(g)} {int(b)}\n")
    return path


class Recorder:
    """把一次 DepthResult 完整落盘。"""

    def __init__(self, out_root: str, save_images: bool = True, save_disparity: bool = True,
                 save_depth: bool = True, save_pointcloud: bool = True,
                 tag: str = "cloud") -> None:
        self.out_root = out_root
        self.save_images = save_images
        self.save_disparity = save_disparity
        self.save_depth = save_depth
        self.save_pointcloud = save_pointcloud
        self.tag = tag

    def save(self, result: DepthResult, meta_extra: Optional[Dict[str, Any]] = None) -> str:
        os.makedirs(self.out_root, exist_ok=True)
        d = make_session_dir(self.out_root, self.tag)
        files = []
        if self.save_images and result.frame is not None:
            for name, img in (("left_raw.png", result.frame.left), ("right_raw.png", result.frame.right)):
                p = os.path.join(d, name)
                cv2.imwrite(p, img)
                files.append(name)
        if self.save_disparity:
            np.save(os.path.join(d, "disparity.npy"), result.disparity)
            files.append("disparity.npy")
        if self.save_depth:
            np.save(os.path.join(d, "depth_meter.npy"), result.depth)
            np.save(os.path.join(d, "valid.npy"), result.valid)
            valid = result.valid
            med = float(np.median(result.depth[valid])) if valid.any() else 0.0
            with open(os.path.join(d, "depth_meter.txt"), "w", encoding="utf-8") as fh:
                fh.write("深度图：depth_meter.npy（float32，单位米，0=无效）\n")
                fh.write(f"有效像素: {int(valid.sum())} / {valid.size} "
                         f"({100.0 * valid.mean():.1f}%)\n")
                fh.write(f"中位深度: {med:.4f} m\n")
                fh.write("另存 valid.npy（bool），判有效性请用它\n")
            files += ["depth_meter.npy", "valid.npy", "depth_meter.txt"]
        if self.save_pointcloud and len(result.points):
            p = write_ascii_ply(os.path.join(d, "cloud.ply"), result.points, result.colors,
                                comments=["units: meters",
                                          "coords: camera frame, x right, y DOWN, z forward",
                                          "colors: RGB, from left image",
                                          "generated by stereo_sdk.Recorder"])
            files.append("cloud.ply")
        meta = {"seq": int(result.seq), "preset": result.preset, "scale": float(result.scale),
                "timings_ms": {k: round(float(v), 3) for k, v in (result.timings or {}).items()},
                "points": int(len(result.points)),
                "disparity_shape": list(result.disparity.shape),
                "depth_shape": list(result.depth.shape),
                "images_are_rectified": True,
                "saved_at": time.strftime("%Y-%m-%d %H:%M:%S")}
        if meta_extra:
            meta.update(meta_extra)
        with open(os.path.join(d, "meta.txt"), "w", encoding="utf-8") as fh:
            json.dump(meta, fh, ensure_ascii=False, indent=2)
        return d
